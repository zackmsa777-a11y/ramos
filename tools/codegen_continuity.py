#!/usr/bin/env python3
"""Verify a usability release preserves the measured benchmark machine code."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--baseline-compiler', required=True, type=Path)
    parser.add_argument('--compiler', type=Path, default=ROOT / 'ramos')
    parser.add_argument('--output', type=Path, default=ROOT / 'build/codegen-continuity.json')
    args = parser.parse_args()
    compilers = {'baseline': args.baseline_compiler.resolve(), 'current': args.compiler.resolve()}
    digest = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
    programs = {}
    with tempfile.TemporaryDirectory() as tmp:
        for source in sorted((ROOT / 'benchmarks/fixtures').glob('*.ramos')):
            for target in ('linux', 'windows'):
                binaries = {}
                for name, compiler in compilers.items():
                    output = Path(tmp) / f'{name}-{source.stem}-{target}'
                    subprocess.run([str(compiler), 'build', str(source), '-o', str(output),
                                    '--target', target], check=True, capture_output=True, timeout=10)
                    binaries[name] = output.read_bytes()
                if binaries['baseline'] != binaries['current']:
                    raise SystemExit(f'Generated bytes changed for {source.stem}/{target}')
                programs[f'{source.stem}/{target}'] = {
                    'source_sha256': digest(source),
                    'binary_sha256': hashlib.sha256(binaries['current']).hexdigest(),
                    'bytes': len(binaries['current']), 'identical': True}
    report = {'compilers': {name: {'sha256': digest(p), 'version': subprocess.check_output(
                  [str(p), '--version'], text=True).strip()} for name, p in compilers.items()},
              'programs': programs, 'all_identical': True,
              'meaning': 'Executable bytes for the old workloads are unchanged; no new timing claim.'}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + '\n')
    print(f'All {len(programs)} workload/target executable pairs are byte-identical.')


if __name__ == '__main__':
    main()
